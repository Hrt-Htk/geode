import { build, context } from "npm:esbuild";
import { builtinModules } from "node:module";
import path from "node:path";
import { encodeBase64 } from "jsr:@std/encoding/base64";
import { stampManifest } from "./manifest-stamp.ts";

const watch = Deno.args.includes("--watch");
const rootDir = Deno.cwd();
const entryPoint = path.join(rootDir, "plugin", "main.ts");
const outDir = path.join(rootDir, "plugin-dist");
const manifestSrc = path.join(rootDir, "manifest.json");
const manifestDest = path.join(outDir, "manifest.json");
const external = [
  "obsidian",
  "electron",
  ...builtinModules,
  ...builtinModules.map((name) => `node:${name}`),
];
const aliases = new Map<string, string>([
  ["@noble/hashes/blake3", path.join(rootDir, "node_modules", "@noble", "hashes", "blake3.js")],
  ["@noble/hashes/hkdf", path.join(rootDir, "node_modules", "@noble", "hashes", "hkdf.js")],
  ["@noble/hashes/sha2", path.join(rootDir, "node_modules", "@noble", "hashes", "sha2.js")],
  [
    "libsodium-wrappers-sumo",
    path.join(
      rootDir,
      "node_modules",
      "libsodium-wrappers-sumo",
      "dist",
      "modules-sumo",
      "libsodium-wrappers.js",
    ),
  ],
]);

const copyAssetsPlugin = {
  name: "copy-plugin-assets",
  setup(buildApi) {
    for (const [specifier, target] of aliases) {
      buildApi.onResolve(
        { filter: new RegExp(`^${escapeRegex(specifier)}$`) },
        () => ({ path: target }),
      );
    }
    buildApi.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      await syncAssets();
    });
  },
};

const options = {
  entryPoints: [entryPoint],
  outfile: path.join(outDir, "main.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  sourcemap: true,
  logLevel: "info" as const,
  external,
  plugins: [copyAssetsPlugin],
};

await Deno.mkdir(outDir, { recursive: true });
// Remove only generated files: never touch data.json (Obsidian vault settings)
for (const file of ["main.js", "main.js.map", "manifest.json", "styles.css", "versions.json"]) {
  const p = path.join(outDir, file);
  await Deno.remove(p).catch(() => {});
}

const generatedDir = path.join(rootDir, "plugin", "_generated");
await Deno.mkdir(generatedDir, { recursive: true });

// Generate base64-inlined libsodium WASM + a patched libsodium-sumo. The Electron
// renderer can't fetch the .wasm (it hangs), so we extract the wasm the Emscripten
// JS already embeds, inline it, and force synchronous instantiation from those bytes.
const sodiumSrcPath = path.join(
  rootDir,
  "node_modules",
  "libsodium-sumo",
  "dist",
  "modules-sumo",
  "libsodium-sumo.js",
);
const sodiumSrc = await Deno.readTextFile(sodiumSrcPath);
const sodiumWasm = extractEmbeddedWasm(sodiumSrc);
await Deno.writeTextFile(
  path.join(generatedDir, "libsodium-wasm-base64.ts"),
  `// AUTO-GENERATED by scripts/plugin-build.ts. Do not edit.
export const LIBSODIUM_WASM_BASE64 = "${encodeBase64(sodiumWasm)}";
`,
);
const sodiumPatchAnchor = "var Module = exports;";
if (!sodiumSrc.includes(sodiumPatchAnchor)) {
  throw new Error("libsodium: patch anchor not found: " + sodiumPatchAnchor);
}
const patchedSodium = sodiumSrc.replace(
  sodiumPatchAnchor,
  sodiumPatchAnchor +
    'if(typeof globalThis.__GEODE_LIBSODIUM_WASM__!=="undefined"){' +
    "Module.wasmBinary=globalThis.__GEODE_LIBSODIUM_WASM__;" +
    "Module.instantiateWasm=function(imports,cb){" +
    "var inst=new WebAssembly.Instance(" +
    "new WebAssembly.Module(globalThis.__GEODE_LIBSODIUM_WASM__),imports);" +
    "cb(inst);return inst.exports;};}",
);
const patchedSodiumPath = path.join(generatedDir, "libsodium-sumo-patched.cjs");
await Deno.writeTextFile(patchedSodiumPath, patchedSodium);
aliases.set("libsodium-sumo", patchedSodiumPath);

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  await new Promise(() => {});
} else {
  await build(options);
}

async function syncAssets() {
  await Deno.mkdir(outDir, { recursive: true });
  // #22: the released version from package.json, not the root manifest's: that
  // one stays on the last promoted version until `deno task promote` moves it.
  const pkg = JSON.parse(await Deno.readTextFile(path.join(rootDir, "package.json"))) as {
    version: string;
  };
  await Deno.writeTextFile(
    manifestDest,
    stampManifest(await Deno.readTextFile(manifestSrc), pkg.version),
  );

  const versionsSrc = path.join(rootDir, "versions.json");
  const versionsDest = path.join(outDir, "versions.json");
  await Deno.stat(versionsSrc)
    .then(() => Deno.copyFile(versionsSrc, versionsDest))
    .catch(() => {});

  const stylesSrc = path.join(rootDir, "plugin", "manifest", "styles.css");
  const stylesDest = path.join(outDir, "styles.css");
  await Deno.stat(stylesSrc)
    .then(() => Deno.copyFile(stylesSrc, stylesDest))
    .catch(() => {});
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Extract the WASM bytes that libsodium-sumo's Emscripten build embeds as a
// `binaryDecode('...')` string literal. binaryDecode is identity for code points
// 0..255, so each char code is one byte. Verified byte-identical to the bundled blob.
function extractEmbeddedWasm(src: string): Uint8Array {
  const marker = "findWasmBinary(){return binaryDecode('";
  const start = src.indexOf(marker);
  if (start === -1) throw new Error("libsodium: embedded wasm marker not found");
  const bodyStart = start + marker.length;
  let i = bodyStart;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === "\\") {
      i++;
      continue;
    }
    if (c === "'") break;
  }
  const body = src.slice(bodyStart, i);
  // deno-lint-ignore no-eval
  const decoded = (0, eval)("'" + body + "'") as string;
  const bytes = new Uint8Array(decoded.length);
  for (let k = 0; k < decoded.length; k++) bytes[k] = decoded.charCodeAt(k) & 0xff;
  if (
    !(bytes[0] === 0x00 && bytes[1] === 0x61 && bytes[2] === 0x73 && bytes[3] === 0x6d)
  ) {
    throw new Error("libsodium: extracted bytes are not a WASM module");
  }
  return bytes;
}
