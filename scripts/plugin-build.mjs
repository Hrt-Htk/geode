import { build, context } from "esbuild";
import { copyFile, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import path from "node:path";
import { findLoadTimeNodeRequires } from "./bundle-node-requires.mjs";
import { stampManifest } from "./manifest-stamp.mjs";
import { generateReleaseNotesModule, readReleaseNotesDir } from "./release-notes-bundle.mjs";

const watch = process.argv.includes("--watch");
const rootDir = process.cwd();
const entryPoint = path.join(rootDir, "plugin", "main.ts");
const outDir = path.join(rootDir, "plugin-dist");
const manifestSrc = path.join(rootDir, "manifest.json");
const manifestDest = path.join(outDir, "manifest.json");
const external = [
  "obsidian",
  "electron",
  ...builtinModules,
  ...builtinModules.map((name) => `node:${name}`),
];
const aliases = new Map([
  ["@noble/hashes/blake3", path.join(rootDir, "node_modules", "@noble", "hashes", "blake3.js")],
  ["@noble/hashes/hkdf", path.join(rootDir, "node_modules", "@noble", "hashes", "hkdf.js")],
  ["@noble/hashes/sha2", path.join(rootDir, "node_modules", "@noble", "hashes", "sha2.js")],
  [
    "libsodium-wrappers-sumo",
    path.join(
      rootDir,
      "node_modules",
      "libsodium-wrappers-sumo",
      "dist",
      "modules-sumo",
      "libsodium-wrappers.js",
    ),
  ],
]);

const copyAssetsPlugin = {
  name: "copy-plugin-assets",
  setup(buildApi) {
    for (const [specifier, target] of aliases) {
      buildApi.onResolve(
        { filter: new RegExp(`^${escapeRegex(specifier)}$`) },
        () => ({ path: target }),
      );
    }
    buildApi.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      await syncAssets();
    });
  },
};

const options = {
  entryPoints: [entryPoint],
  outfile: path.join(outDir, "main.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  sourcemap: true,
  preserveSymlinks: true,
  logLevel: "info",
  external,
  // Dynamic imports compile to a lazy require at the call site. A native ESM
  // `import("node:...")` inside the CJS bundle fails in Obsidian's renderer ("Failed to
  // fetch dynamically imported module", gate6 export spec, #15).
  supported: { "dynamic-import": false },
  plugins: [copyAssetsPlugin],
};

await mkdir(outDir, { recursive: true });
// Remove only generated files: never touch data.json (Obsidian vault settings)
for (const file of ["main.js", "main.js.map", "manifest.json", "styles.css", "versions.json"]) {
  await rm(path.join(outDir, file), { force: true });
}

const generatedDir = path.join(rootDir, "plugin", "_generated");
await mkdir(generatedDir, { recursive: true });

// #93: bundle docs/releases/X.Y.Z.md deterministically into the plugin build.
const releaseNotes = await readReleaseNotesDir(path.join(rootDir, "docs", "releases"));
await writeFile(
  path.join(generatedDir, "release-notes.ts"),
  generateReleaseNotesModule(releaseNotes),
);

// Generate base64-inlined libsodium WASM + a patched libsodium-sumo. The Electron
// renderer can't fetch the .wasm (it hangs), so we extract the wasm the Emscripten
// JS already embeds, inline it, and force synchronous instantiation from those bytes.
// Also strip Emscripten's unused Node `require("fs")` fallback (#80).
const sodiumSrcPath = path.join(
  rootDir,
  "node_modules",
  "libsodium-sumo",
  "dist",
  "modules-sumo",
  "libsodium-sumo.js",
);
const sodiumSrc = await readFile(sodiumSrcPath, "utf8");
const sodiumWasm = extractEmbeddedWasm(sodiumSrc);
await writeFile(
  path.join(generatedDir, "libsodium-wasm-base64.ts"),
  `// AUTO-GENERATED by scripts/plugin-build.mjs. Do not edit.
export const LIBSODIUM_WASM_BASE64 = "${Buffer.from(sodiumWasm).toString("base64")}";
`,
);
const sodiumPatchAnchor = "var Module = exports;";
if (!sodiumSrc.includes(sodiumPatchAnchor)) {
  throw new Error("libsodium: patch anchor not found: " + sodiumPatchAnchor);
}
const sodiumFsRequire = 'var fs=require("fs");';
if (!sodiumSrc.includes(sodiumFsRequire)) {
  throw new Error("libsodium: fs require anchor not found: " + sodiumFsRequire);
}
const patchedSodium = sodiumSrc
  .replace(
    sodiumPatchAnchor,
    sodiumPatchAnchor +
      'if(typeof globalThis.__GEODE_LIBSODIUM_WASM__!=="undefined"){' +
      "Module.wasmBinary=globalThis.__GEODE_LIBSODIUM_WASM__;" +
      "Module.instantiateWasm=function(imports,cb){" +
      "var inst=new WebAssembly.Instance(" +
      "new WebAssembly.Module(globalThis.__GEODE_LIBSODIUM_WASM__),imports);" +
      "cb(inst);return inst.exports;};}",
  )
  .replaceAll(sodiumFsRequire, "var fs;");
if (/require\(["']fs["']\)/.test(patchedSodium)) {
  throw new Error("libsodium: unexpected require('fs') remains after patch");
}
const patchedSodiumPath = path.join(generatedDir, "libsodium-sumo-patched.cjs");
await writeFile(patchedSodiumPath, patchedSodium);
aliases.set("libsodium-sumo", patchedSodiumPath);

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  await new Promise(() => {});
} else {
  await build(options);
  // #15: Node's modules do not exist on mobile and the community scanner forbids a Node
  // import at load, so a bundle that carries one must not ship. Dynamic imports stay
  // inside functions and are not load-time requires.
  const loadTime = findLoadTimeNodeRequires(await readFile(options.outfile, "utf8"));
  if (loadTime.length > 0) {
    throw new Error(`main.js requires Node modules at load: ${loadTime.join(", ")}`);
  }
}

async function syncAssets() {
  await mkdir(outDir, { recursive: true });
  // #22: the released version from package.json, not the root manifest's: that
  // one stays on the last promoted version until `deno task promote` moves it.
  const pkg = JSON.parse(await readFile(path.join(rootDir, "package.json"), "utf8"));
  await writeFile(
    manifestDest,
    stampManifest(await readFile(manifestSrc, "utf8"), pkg.version),
  );

  const versionsSrc = path.join(rootDir, "versions.json");
  const versionsDest = path.join(outDir, "versions.json");
  await stat(versionsSrc)
    .then(() => copyFile(versionsSrc, versionsDest))
    .catch(() => {});

  const stylesSrc = path.join(rootDir, "plugin", "manifest", "styles.css");
  const stylesDest = path.join(outDir, "styles.css");
  await stat(stylesSrc)
    .then(() => copyFile(stylesSrc, stylesDest))
    .catch(() => {});
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Extract the WASM bytes that libsodium-sumo's Emscripten build embeds as a
// `binaryDecode('...')` string literal. binaryDecode is identity for code points
// 0..255, so each char code is one byte. Verified byte-identical to the bundled blob.
function extractEmbeddedWasm(src) {
  const marker = "findWasmBinary(){return binaryDecode('";
  const start = src.indexOf(marker);
  if (start === -1) throw new Error("libsodium: embedded wasm marker not found");
  const bodyStart = start + marker.length;
  let i = bodyStart;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === "\\") {
      i++;
      continue;
    }
    if (c === "'") break;
  }
  const body = src.slice(bodyStart, i);
  const decoded = (0, eval)("'" + body + "'");
  const bytes = new Uint8Array(decoded.length);
  for (let k = 0; k < decoded.length; k++) bytes[k] = decoded.charCodeAt(k) & 0xff;
  if (
    !(bytes[0] === 0x00 && bytes[1] === 0x61 && bytes[2] === 0x73 && bytes[3] === 0x6d)
  ) {
    throw new Error("libsodium: extracted bytes are not a WASM module");
  }
  return bytes;
}
